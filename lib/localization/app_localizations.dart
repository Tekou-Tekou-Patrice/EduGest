  static Set<String> get translationKeys => _localizedValues.values
      .expand((translations) => translations.keys)
      .toSet();

  static bool hasTranslation(String languageCode, String key) =>
      _localizedValues[languageCode]?.containsKey(key) ?? false;

  String translate(String key) {
    return _localizedValues[locale.languageCode]?[key] ??
        _localizedValues['fr']?[key] ??
        _fallbackTranslation(key);
  }

  String translateRole(String role, {String? schoolLevel}) {
    if ((schoolLevel ?? '').toUpperCase() == 'PRIMARY') {
      if (role == 'enseignant') return translate('role_primaryTeacher');
      if (role == 'proviseur') return translate('role_primaryDirector');
    }
    return translate('role_$role');
  }

  String translateAcademicPeriod(String period) {
    switch (period) {
      case '1er Trimestre':
        return translate('periodTerm1');
      case '2ème Trimestre':
        return translate('periodTerm2');
      case '3ème Trimestre':
        return translate('periodTerm3');
      case 'Bilan Annuel':
        return translate('periodAnnual');
      default:
        if (period.startsWith('Séquence ')) {
          return '${translate('periodSequence')} ${period.split(' ').last}';
        }
        return period;
    }
  }

  String translateAbsencePeriod(String period) {
    switch (period) {
      case 'Matin':
        return translate('morning');
      case 'Après-midi':
        return translate('afternoon');
      case 'Journée complète':
        return translate('fullDay');
      default:
        return period;
    }
  }

  String _fallbackTranslation(String key) {
    const common = {
      'emailOrPhone': {
        'fr': 'E-mail ou numéro de téléphone',
        'en': 'Email or phone number',
      },
      'forgotPassword': {
        'fr': 'Mot de passe oublié ?',
        'en': 'Forgot password?',
      },
      'auto_mot_de_passe_oublie': {
        'fr': 'Mot de passe oublié ?',
        'en': 'Forgot password?',
      },
      'auto_appliquer': {'fr': 'Appliquer', 'en': 'Apply'},
      'auto_enseignant': {'fr': 'Enseignant', 'en': 'Teacher'},
      'auto_titre': {'fr': 'Titre', 'en': 'Title'},
      'auto_vie_scolaire': {'fr': 'Vie scolaire', 'en': 'School life'},
      'auto_communication': {'fr': 'Communication', 'en': 'Communication'},
    };
    final direct = common[key];
    if (direct != null) {
      return direct[locale.languageCode] ?? direct['en']!;
    }

    final words = key
        .replaceFirst(RegExp(r'^auto_'), '')
        .replaceAllMapped(
          RegExp(r'([a-z])([A-Z])'),
          (match) => '${match.group(1)} ${match.group(2)}',
        )
        .replaceAll('_', ' ')
        .trim();
    if (words.isEmpty) return key;
    return words[0].toUpperCase() + words.substring(1);
  }
